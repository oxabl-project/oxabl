//! Compile `resources/progress_builtin_classes.json` into the static table the
//! semantic resolver looks built-in class names up in.
//!
//! The JSON stays the checked-in source of truth; the table is a sorted
//! `&'static` slice, so a lookup costs no startup parse and pulls no JSON
//! parser into the WASM payload. Members are not compiled yet: only the names,
//! kinds and supertypes are.

use std::fmt::Write as _;

use crate::progress_docs::{BuiltinIndex, TypeKind};

/// The JSON the table is compiled from, relative to the workspace root.
pub const JSON_PATH: &str = "resources/progress_builtin_classes.json";
/// The generated table, relative to the workspace root.
pub const TABLE_RS_PATH: &str = "crates/oxabl_semantic/src/builtin_classes.rs";

/// One table row, in lookup order.
struct Row<'a> {
    key: String,
    name: &'a str,
    kind: &'static str,
    type_params: Vec<&'a str>,
    inherits: Option<&'a str>,
    implements: &'a [String],
}

/// Read the JSON index at `path`.
pub fn read_index(path: &std::path::Path) -> Result<BuiltinIndex, String> {
    let text =
        std::fs::read_to_string(path).map_err(|e| format!("reading {}: {e}", path.display()))?;
    serde_json::from_str(&text).map_err(|e| format!("parsing {}: {e}", path.display()))
}

/// Split `HashMap<K,V>` into `HashMap` and `["K", "V"]`.
fn split_generic(name: &str) -> (&str, Vec<&str>) {
    match name.split_once('<') {
        Some((base, rest)) => (
            base,
            rest.trim_end_matches('>')
                .split(',')
                .map(str::trim)
                .filter(|p| !p.is_empty())
                .collect(),
        ),
        None => (name, Vec::new()),
    }
}

/// A string slice literal, laid out the way rustfmt lays out a struct field
/// holding one at `indent`: on one line while the array fits rustfmt's
/// 60-column `array_width` (the items, without the brackets), otherwise one item per line.
fn str_slice(field: &str, items: &[&str], indent: usize) -> String {
    let pad = " ".repeat(indent);
    let inner = items
        .iter()
        .map(|s| format!("{s:?}"))
        .collect::<Vec<_>>()
        .join(", ");
    let one_line = format!("{pad}{field}: &[{inner}],");
    if inner.len() <= 60 && one_line.len() <= 100 {
        return format!("{one_line}\n");
    }
    let mut out = format!("{pad}{field}: &[\n");
    for item in items {
        let _ = writeln!(out, "{pad}    {item:?},");
    }
    let _ = writeln!(out, "{pad}],");
    out
}

/// Generate `builtin_classes.rs` from `index`.
pub fn generate(index: &BuiltinIndex) -> Result<String, String> {
    let mut rows: Vec<Row> = index
        .types
        .iter()
        .map(|(name, entry)| {
            let (base, type_params) = split_generic(name);
            Row {
                key: base.to_ascii_lowercase(),
                name: base,
                kind: match entry.kind {
                    TypeKind::Class => "Class",
                    TypeKind::Interface => "Interface",
                    TypeKind::Enum => "Enum",
                },
                type_params,
                inherits: entry.inherits.as_deref(),
                implements: &entry.implements,
            }
        })
        .collect();
    rows.sort_by(|a, b| a.key.cmp(&b.key));
    if let Some(pair) = rows.windows(2).find(|w| w[0].key == w[1].key) {
        return Err(format!(
            "two built-in types share the lookup key `{}`",
            pair[0].key
        ));
    }

    let mut out = String::new();
    out.push_str("// Generated by oxabl_codegen - DO NOT EDIT\n\n");
    let _ = writeln!(
        out,
        "//! The documented OpenEdge {} built-in classes, interfaces and enums.",
        index.version
    );
    out.push_str(
        "//!
//! Compiled from `resources/progress_builtin_classes.json` by
//! `cargo run -p oxabl_codegen -- builtin-class-table`. A name is looked up
//! case-insensitively and without its generic parameters, the way ABL source
//! names a type: `progress.collections.hashmap` finds `HashMap<K,V>`.

use std::cmp::Ordering;

use crate::ClassKind;

/// One documented built-in type.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[non_exhaustive]
pub struct BuiltinClass {
    /// The lookup key: the name folded to lowercase.
    key: &'static str,
    /// The qualified name as documented, without generic parameters.
    pub name: &'static str,
    pub kind: ClassKind,
    /// The generic type parameters, `[\"K\", \"V\"]` for `HashMap<K,V>`.
    pub type_params: &'static [&'static str],
    /// The parent class or super-interface, as documented. A .NET parent
    /// (`System.Object`) names no type in this table.
    pub inherits: Option<&'static str>,
    /// The implemented interfaces, as documented.
    pub implements: &'static [&'static str],
}

/// The documented built-in type named `name`, which may be written in any case
/// and with generic arguments.
pub fn builtin_class(name: &str) -> Option<&'static BuiltinClass> {
    builtin_class_in(\"\", name)
}

/// [`builtin_class`] for the name `prefix` followed by `name`, without
/// building the joined string.
pub(crate) fn builtin_class_in(prefix: &str, name: &str) -> Option<&'static BuiltinClass> {
    let name = name.split_once('<').map_or(name, |(base, _)| base);
    BUILTIN_CLASSES
        .binary_search_by(|class| compare_folded(class.key, prefix, name))
        .ok()
        .map(|i| &BUILTIN_CLASSES[i])
}

fn compare_folded(key: &str, prefix: &str, name: &str) -> Ordering {
    let wanted = prefix
        .bytes()
        .chain(name.bytes())
        .map(|b| b.to_ascii_lowercase());
    key.bytes().cmp(wanted)
}

",
    );
    let _ = writeln!(
        out,
        "/// Sorted by `key` ({} entries).\nstatic BUILTIN_CLASSES: &[BuiltinClass] = &[",
        rows.len()
    );
    for row in &rows {
        out.push_str("    BuiltinClass {\n");
        let _ = writeln!(out, "        key: {:?},", row.key);
        let _ = writeln!(out, "        name: {:?},", row.name);
        let _ = writeln!(out, "        kind: ClassKind::{},", row.kind);
        out.push_str(&str_slice("type_params", &row.type_params, 8));
        match row.inherits {
            Some(parent) => {
                let _ = writeln!(out, "        inherits: Some({parent:?}),");
            }
            None => out.push_str("        inherits: None,\n"),
        }
        let implements: Vec<&str> = row.implements.iter().map(String::as_str).collect();
        out.push_str(&str_slice("implements", &implements, 8));
        out.push_str("    },\n");
    }
    out.push_str("];\n");
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generated_table_matches_checked_in_catalog() {
        let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
        let index = read_index(&root.join(JSON_PATH)).unwrap();
        let expected = std::fs::read_to_string(root.join(TABLE_RS_PATH)).unwrap();
        assert_eq!(generate(&index).unwrap(), expected);
    }

    #[test]
    fn generic_names_split_into_base_and_parameters() {
        assert_eq!(
            split_generic("Progress.Collections.HashMap<K,V>"),
            ("Progress.Collections.HashMap", vec!["K", "V"])
        );
        assert_eq!(
            split_generic("Progress.Lang.Object"),
            ("Progress.Lang.Object", vec![])
        );
    }

    #[test]
    fn a_long_slice_breaks_one_item_per_line() {
        assert_eq!(
            str_slice("implements", &["A", "B"], 8),
            "        implements: &[\"A\", \"B\"],\n"
        );
        let long = "OpenEdge.Core.Collections.IStringStringMap";
        assert_eq!(
            str_slice("implements", &[long, long], 8),
            format!(
                "        implements: &[\n            {long:?},\n            {long:?},\n        ],\n"
            )
        );
    }
}
